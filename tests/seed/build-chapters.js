const chapterRows = []
Object.keys(chapterTree).forEach(subjectCode => {
  const groups = chapterTree[subjectCode]
  groups.forEach((group, gi) => {
    const gCode = group[0]
    const gParent = group[1]
    const gName = group[2]
    const leaves = group[3] || []
    chapterRows.push([subjectCode, gCode, gParent === '' ? null : gParent, gName, gParent === '' ? 1 : 2, (gi + 1) * 100])
    leaves.forEach((leaf, li) => {
      chapterRows.push([subjectCode, leaf[0], gCode, leaf[1], gParent === '' ? 2 : 3, (gi + 1) * 100 + li + 1])
    })
  })
})

fs.writeFileSync(
  path.join(OUT, 'chapters.sql'),
  'INSERT INTO chapters (subject_code, code, parent_code, name, level, sort_order) VALUES\n' +
    chapterRows.map(r => '  (' + r.map(q).join(', ') + ')').join(',\n') + ';'
)

